const languageNames = { ru: 'RU', hy: 'Հայ', en: 'EN' };
const languageMenu = document.querySelector('.language-switcher');
const languageButtons = [...document.querySelectorAll('[data-set-language]')];

function applyLanguage(language) {
  const dictionary = translations[language] || translations.ru;
  document.documentElement.lang = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.querySelectorAll('[data-i18n-attr]').forEach((element) => {
    element.dataset.i18nAttr.split(',').forEach((entry) => {
      const [attribute, key] = entry.split(':');
      if (dictionary[key]) element.setAttribute(attribute, dictionary[key]);
    });
  });

  document.querySelector('[data-current-language]').textContent = languageNames[language] || 'RU';
  languageButtons.forEach((button) => {
    button.setAttribute('aria-pressed', String(button.dataset.setLanguage === language));
  });

  try { localStorage.setItem('melo-storefront-language', language); } catch { /* Storage may be unavailable in private browsing. */ }
}

languageButtons.forEach((button) => {
  button.addEventListener('click', () => {
    applyLanguage(button.dataset.setLanguage);
    languageMenu.open = false;
  });
});

let initialLanguage = 'ru';
try {
  const savedLanguage = localStorage.getItem('melo-storefront-language');
  if (savedLanguage && translations[savedLanguage]) initialLanguage = savedLanguage;
} catch { /* Keep Russian as the default if storage is unavailable. */ }
applyLanguage(initialLanguage);
